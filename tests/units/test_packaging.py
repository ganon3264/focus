"""Packaging guards: the pip fallback path in start.sh/test.sh must be able to
install a working environment from requirements.lock.txt alone.

The lock is generated by hand (`uv pip compile pyproject.toml --all-extras
--generate-hashes -o requirements.lock.txt`), so it drifts when a dependency is
added to pyproject and nobody regenerates it — at which point uv users are fine
and everyone else gets an ImportError at startup.
"""

import re
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REQUIREMENT = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;]+)")


def _normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _direct_dependencies() -> dict[str, str]:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    groups = {"dependencies": project.get("dependencies", [])}
    groups.update(project.get("optional-dependencies", {}))
    deps = {}
    for extra, entries in groups.items():
        for entry in entries:
            name = re.split(r"[<>=!~\[\s;]", entry, maxsplit=1)[0]
            deps[name] = extra
    return deps


def _locked() -> dict[str, str]:
    locked = {}
    for line in (ROOT / "requirements.lock.txt").read_text().splitlines():
        match = REQUIREMENT.match(line)
        if match:
            locked[_normalise(match.group(1))] = match.group(2)
    return locked


def test_lock_covers_every_direct_dependency():
    locked = _locked()
    missing = [
        f"{name} (from {extra})"
        for name, extra in _direct_dependencies().items()
        if _normalise(name) not in locked
    ]
    assert not missing, f"requirements.lock.txt is stale, missing: {', '.join(missing)}"
